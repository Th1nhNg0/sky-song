import type { SoundProfileId } from '../music/types';

type PartialSpec = readonly [ratio: number, amplitude: number, decayScale?: number];

interface NoiseSpec {
  amount: number;
  type: BiquadFilterType;
  frequency: number;
  q: number;
  decay: number;
}

export interface SynthProfile {
  kind: 'pluck' | 'struck' | 'blow' | 'sustain' | 'percussion';
  osc: OscillatorType;
  partials: readonly PartialSpec[];
  attack: number;
  decay: number;
  sustainLevel: number;
  release: number;
  naturalDecay: number;
  minHold: number;
  maxHold: number;
  lowpass: number;
  q: number;
  /** Filter-bloom multiplier at note start; 1 = no bloom. */
  filterFrom: number;
  /** Seconds for the filter bloom to settle at the nominal cutoff. */
  filterDecay: number;
  /** Extra quiet air after the main decay, in seconds. */
  tail: number;
  /** Sustained breath/air noise bed (winds, choir). */
  breath?: NoiseSpec;
  vibratoRate: number;
  vibratoCents: number;
  detuneSpread: number;
  ensemble: number;
  noise?: NoiseSpec;
  gain: number;
  distortion?: number;
}

