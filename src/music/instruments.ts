export const INSTRUMENTS: InstrumentDefinition[] = SEEDS.map(makeInstrument);

const INSTRUMENT_MAP: ReadonlyMap<string, InstrumentDefinition> = new Map(
  INSTRUMENTS.map((instrument) => [instrument.id, instrument]),
);

export const DEFAULT_INSTRUMENT_ID = 'harp';

const FALLBACK_INSTRUMENT = INSTRUMENT_MAP.get(DEFAULT_INSTRUMENT_ID)!;

export function getInstrument(id: string): InstrumentDefinition {
  return INSTRUMENT_MAP.get(id) ?? FALLBACK_INSTRUMENT;
}

export function hasInstrument(id: string): boolean {
  return INSTRUMENT_MAP.has(id);
}

export function selectableInstruments(): InstrumentDefinition[] {
  return INSTRUMENTS.filter((instrument) => instrument.selectable);
}

export interface CatalogFilters {
  query?: string;
  part?: SheetPart | 'all';
  status?: InstrumentStatus | 'all';
  category?: string | 'all';
}

export function searchInstruments(filters: CatalogFilters = {}): InstrumentDefinition[] {
  const query = (filters.query ?? '').trim().toLowerCase();
  return selectableInstruments().filter((instrument) => {
    if (filters.part && filters.part !== 'all' && instrument.nativeSheetPart !== filters.part) return false;
    if (filters.status && filters.status !== 'all' && instrument.status !== filters.status) return false;
    if (filters.category && filters.category !== 'all' && instrument.category !== filters.category) return false;
    if (!query) return true;
    const haystack = [
      instrument.displayName,
      instrument.shortName,
      instrument.category,
      instrument.nativePartCode,
      instrument.nativeSheetPart,
      instrument.confidence,
      instrument.status,
      ...instrument.aliases,
      instrument.notes ?? '',
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(query);
  });
}
