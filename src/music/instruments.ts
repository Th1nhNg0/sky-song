interface Seed {
  id: string;
  name: string;
  short?: string;
  category: string;
  part: SheetPart;
  code: string;
  pattern?: 'standard-15' | 'bells-8' | 'handpan-8' | 'krill-8';
  count?: 15 | 8 | 4;
  drums?: PercussionVoiceId[] | 'drums-8' | 'drums-4' | 'cymbals-4';
  octave?: number;
  hold?: boolean;
  profile: SoundProfileId;
  reverb?: number;
  detune?: number;
  confidence: Confidence;
  status: InstrumentStatus;
  evidence?: string[];
  aliases?: string[];
  notes?: string;
  accent: string;
  selectable?: boolean;
}

function drumPads(kind: Seed['drums']) {
  if (kind === 'drums-8') return unpitchedPads(DRUMS_8);
  if (kind === 'drums-4') return unpitchedPads(DRUMS_4, 2);
  if (kind === 'cymbals-4') return unpitchedPads(CYMBALS_4, 2);
  throw new Error('Unknown drum kind');
}

function padsForSeed(seed: Seed) {
  if (seed.drums) return drumPads(seed.drums);
  if (seed.pattern === 'bells-8') return pitchedPads(BELLS_8_SEMITONES);
  if (seed.pattern === 'handpan-8') return pitchedPads(HANDPAN_8_SEMITONES);
  if (seed.pattern === 'krill-8') return pitchedPads(KRILL_8_SEMITONES);
  if ((seed.count ?? 15) === 15) return pitchedPads(STANDARD_15_SEMITONES);
  if (seed.count === 8) return pitchedPads(BELLS_8_SEMITONES);
  throw new Error(`Cannot build pads for ${seed.id}`);
}

function makeInstrument(seed: Seed): InstrumentDefinition {
  const pads = padsForSeed(seed);
  const count = pads.length;
  const pitched = pads.some((p) => p.pitched);
  const layout = layoutFor(count);
  const evidence = seed.evidence ?? [
    PART_EVIDENCE,
    MUSIC_EVIDENCE,
    NIGHTLY_META,
  ];
  return {
    id: seed.id,
    displayName: seed.name,
    shortName: seed.short ?? seed.name,
    category: seed.category,
    nativeSheetPart: seed.part,
    nativePartCode: seed.code,
    keyCount: count,
    padLayout: layout,
    pads,
    baseOctave: seed.octave ?? 4,
    supportsHold: Boolean(seed.hold),
    soundProfile: seed.profile,
    renderingMode: pitched ? 'pitched' : 'unpitched',
    maxHoldBeats: 16,
    reverbSend: seed.reverb ?? 0.16,
    detuneCents: seed.detune ?? 0,
    evidence,
    confidence: seed.confidence,
    status: seed.status,
    aliases: seed.aliases ?? [],
    notes: seed.notes,
    selectable: seed.selectable ?? true,
    accent: seed.accent,
  };
}

